def land(p):
    x,y=p; n=len(POLY); c=False; j=n-1
    for i in range(n):
        xi,yi=POLY[i]; xj,yj=POLY[j]
        if ((yi>y)!=(yj>y)) and (x < (xj-xi)*(y-yi)/(yj-yi)+xi): c=not c
        j=i
    return c
def _quad(A,C,B,n):
    out=[]
    for i in range(n+1):
        t=i/n; u=1-t
        out.append((u*u*A[0]+2*u*t*C[0]+t*t*B[0], u*u*A[1]+2*u*t*C[1]+t*t*B[1]))
    return out
